const slug = (s: string) => s.toLowerCase().replace(/\+/g, "plus").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

export const SERVICES: Service[] = RAW.map(([name, cats, plans]) => {
  const id = slug(name);
  return {
    id, name, categoryIds: cats,
    plans: plans.map(([p, price, interval = "month"], i) => ({ id: `${id}-${slug(p)}-${i}`, name: p, price, interval })),
  };
});

export const categoryName = (id: string) => CATEGORIES.find((c) => c.id === id)?.name ?? id;
